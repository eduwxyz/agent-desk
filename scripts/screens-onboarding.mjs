// Screenshots of the first-run introduction, step by step, on a new install
// (no sample team), with the fake engines. Then the "Primeiros passos" list.
import { _electron as electron } from 'playwright'
import { mkdirSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
const out = process.argv[2] ?? 'screens'
mkdirSync(out, { recursive: true })
const data = mkdtempSync(join(tmpdir(), 'agent-desk-'))
const app = await electron.launch({ args: ['.'], env: { ...process.env, AGENT_DESK_DATA: data, AGENT_DESK_FAKE_ENGINES: '1', AGENT_DESK_SEED: '0' } })
const win = await app.firstWindow()
await win.setViewportSize({ width: 1360, height: 860 })
const errors = []
win.on('pageerror', (e) => errors.push(String(e)))
win.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const shot = (name) => win.screenshot({ path: `${out}/${name}.png` })
const settle = () => win.waitForTimeout(500)

await win.waitForSelector('.splash')
await win.click('.splash') // skip the opening
await win.waitForSelector('.onb')
await win.fill('.onb__field input', 'Marina')
await settle()
await shot('1-boas-vindas')
await win.click('button:has-text("Começar")')
await settle()
await shot('2-motor')
await win.click('button:has-text("Continuar")')
await settle()
await shot('2b-modelos-vazio')
const picks = win.locator('.onb-pick select')
await picks.nth(0).selectOption('custom:claude')
await win.locator('.onb-pick').nth(0).locator('.model-name').fill('gw-claude-haiku')
await picks.nth(1).selectOption('haiku')
await settle()
await shot('2c-modelos')
await win.click('button:has-text("Continuar")')
await win.fill('.onb__textarea', 'Sou designer numa agência pequena em Curitiba. Cuido de três clientes de e-commerce.')
await win.click('.onb-chip:has-text("Prefiro respostas curtas")')
await settle()
await shot('3-voce')
await win.click('button:has-text("Continuar")')
await win.fill('.onb-add input >> nth=0', 'Jira interno')
await win.fill('.onb-add input >> nth=1', 'https://mcp.lumen.dev/jira')
await win.click('.onb-add .segmented button:has-text("Token")')
await win.fill('.onb-add input[type=password]', 'tok-123')
await win.click('.onb-add button:has-text("Conectar")')
await win.waitForTimeout(1500)
await shot('3b-ferramentas')
await win.click('.onb__nav .btn--primary')
await win.waitForTimeout(800)
await win.locator('.onb-skill').first().click().catch(() => {})
await settle()
await shot('3c-skills')
await win.click('.onb__nav .btn--primary')
await settle()
await shot('4-agente')
await win.click('.onb-template:has-text("Conteúdo")')
await settle()
await shot('4b-agente-conteudo')
await win.click('.onb-template:has-text("Pesquisa")')
await win.click('button:has-text("Continuar")')
await win.click('.onb-power-row:has-text("Navegador") .toggle')
await win.click('.segmented button:has-text("Este Mac")')
await settle()
await shot('5-poderes')
await win.click('.segmented button:has-text("Nenhum")')
await win.click('button:has-text("Continuar")')
await settle()
await shot('6-primeira-tarefa')
await win.click('button:has-text("e enviar")')
await win.waitForSelector('.sidebar')
await win.waitForTimeout(4000)
await shot('7-canal')
await win.click('.getting__bar')
await settle()
await shot('8-primeiros-passos')
await win.click('.getting__list li.is-next button')
await settle()
await shot('9-depois-do-clique')
await win.click('.sidebar button[title="Trocar tema"]')
await win.click('.sidebar__foot .nav-item:has-text("Configurações")')
await win.click('button:has-text("Rever a introdução")')
await win.waitForSelector('.onb')
await settle()
await shot('10-rever-escuro')
await win.click('button:has-text("Começar")')
await settle()
await shot('11-motor-escuro')
console.log('erros:', errors)
await app.close()
